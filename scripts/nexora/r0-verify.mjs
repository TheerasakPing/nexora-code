import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const text=p=>readFileSync(p,'utf8');
const json=p=>JSON.parse(text(p));
const pkg=json('package.json'), tauri=json('src-tauri/tauri.conf.json');
const cap=json('src-tauri/capabilities/default.json');
assert.equal(pkg.name,'nexora-code');
assert.equal(pkg.version,'0.1.0');
assert.equal(tauri.productName,'Nexora Code');
assert.equal(tauri.identifier,'com.theerasakping.nexoracode');
assert.equal(tauri.version,'0.1.0');
assert.equal(pkg.repository.url,'git+https://github.com/TheerasakPing/nexora-code.git');
assert.equal(tauri.plugins?.updater,undefined);
assert.ok(!cap.permissions.includes('updater:default'));
assert.ok(!text('src-tauri/src/lib.rs').includes('.plugin(tauri_plugin_updater::Builder::new().build())'));
assert.ok(text('src/app-updates.ts').includes('const NEXORA_R0_UPDATES_DISABLED = true;'));
assert.ok(!text('src-tauri/src/provider_settings.rs').includes('app.pandacode.providers'));
assert.ok(text('LICENSE').includes('PandaCode License'));
assert.ok(text('README.md').includes('This is a fork of PandaCode'));
assert.ok(text('src/about-settings.ts').includes('This is a fork of PandaCode'));
assert.ok(text('src/about-settings.ts').includes('PROJECT_LINKS.upstream'));
assert.ok(text('src-tauri/Cargo.toml').includes('version = "0.1.0"'));
assert.match(text('src-tauri/Cargo.lock'),/\[\[package\]\]\s+name = "pandacode"\s+version = "0\.1\.0"/);
assert.ok(!existsSync('.github/workflows/release.yml'),'upstream release workflow must not publish fork');
console.log('Nexora Code R0 identity / fork-attribution / updater safety: PASS');
console.log('Native OS / GUI / provider E2E still require independent verification.');
